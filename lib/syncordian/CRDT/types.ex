defmodule Syncordian.Basic_Types do
  @moduledoc """
      This module provides the types used in the Syncordian implementation
  """

  #   use TypeCheck

  @typedoc """
    Status of a Syncordian document line — the join-semilattice chain of the formal model
    (`:aura` ⊏ `:settled` ⊏ `:tombstone`, all changes inflationary joins):

        - :aura: inserted but not yet acknowledged by every trusted peer.

        - :settled: acknowledged by the whole network (its response checklist completed).

        - :tombstone: deleted; kept in the document (neighbor signatures still chain
            through it) but user-invisible. Absorbing: a tombstone is never demoted.
            Lines superseded during an interleaving re-placement are retracted with an
            ordinary delete, i.e. they become tombstones too (`Syncordian.Interleaving`).
  """
  @type status :: :tombstone | :aura | :settled | nil

  @typedoc """
      Type that represents the content of a Syncordian document line
  """
  @type content :: String.t()

  @typedoc """
      Type that represents the signature of a Syncordian document line
  """
  @type signature :: String.t()

  @typedoc """
      Type that represents the vector clock of a Syncordian peer, are the same proposed by
      Lamport in 1978 (?)
  """
  @type vector_clock :: [integer()]

  @typedoc """
    Type that represents the commit list of a Syncordian document line, it is a list of
    boolean values, each value represents the commit status of the line in the peer
    position
  """
  @type commit_list :: [boolean()]

  @typedoc """
      Type that represents the peer id
  """
  @type peer_id :: integer()

  @typedoc """
      Operation identifier stamped on each insert/delete at its origin: a per-peer
      monotonic sequence number paired with the originating peer id. It is stable across
      retransmissions, so a replayed message carries the same `op_id` and is rejected by a
      receiver's bounded seen-set — see `Syncordian.SeenOps`.
  """
  @type op_id :: {peer_id(), non_neg_integer()}

  @typedoc """
      Authoring session of a line: the pair of identities bounding the interval its writer was
      typing into when it started the run of inserts the line belongs to. Together with the
      writer it identifies an authored block (`def:editblock`), and unlike the per-line parent
      pair it survives a re-placement of the block and a delete inside it — see
      `Syncordian.Interleaving`.
  """
  @type session :: {op_id() | nil, op_id() | nil}

  @typedoc """
      Position identifier of a Syncordian document line. Variable-length, totally
      ordered, dense — see `Syncordian.PathId` for the constructors, comparator and
      midpoint allocator.
  """
  @type line_id :: Syncordian.PathId.t()

